'use strict'
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { spawnSync } = require('node:child_process')
const tool = path.join(__dirname, '../src/main/resources/dev/slidev/intellij/load-deck.cjs')
const { load, resolveParser } = require(tool)
const project = path.resolve(process.argv[2] || path.join(__dirname, '../examples'))
const parserRoot = path.dirname(path.dirname(resolveParser(path.join(project, 'slides.md'))))
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'slidev-import-fixture-'))
const entry = path.join(root, 'slides.md')
function file(name, source) { const target = path.join(root, name); fs.mkdirSync(path.dirname(target), { recursive: true }); fs.writeFileSync(target, source); return target }
function titles(deck) { return deck.slides.map(slide => slide.title) }
;(async () => {
  try {
    fs.mkdirSync(path.join(root, 'node_modules/@slidev'), { recursive: true })
    fs.symlinkSync(parserRoot, path.join(root, 'node_modules/@slidev/parser'), process.platform === 'win32' ? 'junction' : 'dir')
    file('package.json', '{}')
    const child = file('parts/a.md', '# A\n---\n# B\n')
    file('slides.md', '# Intro\n---\nsrc: ./parts/a.md\n---\n\n---\n\n# End\n\n---\nsrc: ./parts/a.md#2,1,2\n---\n')
    let deck = await load(entry)
    assert.deepEqual(titles(deck), ['Intro', 'A', 'B', 'End', 'A', 'B'])
    assert.equal(deck.slides[4].sites[0].local, 4)
    assert.equal(deck.slides[1].path, child)
    assert.equal(deck.slides[1].local, 1)
    assert.equal(deck.issues.length, 0)
    const dirty = new Map([[child, '# Unsaved A\n---\n# Unsaved B\n']])
    assert.deepEqual(titles(await load(entry, dirty)), ['Intro', 'Unsaved A', 'Unsaved B', 'End', 'Unsaved A', 'Unsaved B'])
    const nested = file('parts/nested.md', '# Nested\n---\nsrc: ./a.md#2\n---\n')
    file('slides.md', '# Intro\n---\nsrc: ./parts/nested.md#2\n---\n')
    deck = await load(entry)
    assert.deepEqual(titles(deck), ['Intro', 'B'])
    assert.equal(deck.slides[1].sites.length, 2)
    assert.equal(deck.slides[1].sites[1].path, nested)
    file('slides.md', '# Intro\n---\nhide: true\n---\n# Hidden\n---\ndisabled: true\n---\n# Disabled\n---\nsrc: ./parts/a.md\n---\n')
    assert.deepEqual(titles(await load(entry)), ['Intro', 'A', 'B'])
    file('slides.md', '# Intro\n---\nsrc: /parts/a.md#2\n---\n')
    assert.deepEqual(titles(await load(entry)), ['Intro', 'B'])
    file('slides.md', '# Intro\n---\nsrc: ./missing.md\n---\n')
    deck = await load(entry)
    assert(deck.issues.length && deck.watched.has(path.join(root, 'missing.md')))
    file('slides.md', '# Intro\n---\nsrc: ./parts/cycle.md\n---\n')
    file('parts/cycle.md', '---\nsrc: ../slides.md\n---\n')
    assert((await load(entry)).issues.some(issue => /Cyclic/.test(issue.message)))
    file('slides.md', '# Intro\n---\nsrc: ./parts/broken.md\n---\n')
    const broken = file('parts/broken.md', '---\nlayout: [broken\n---\n# Bad\n')
    deck = await load(entry)
    assert(deck.sources.has(broken) && deck.watched.has(broken))
    file('slides.md', '---\ntheme: default\n---\n# 🐇 Intro\n---\nsrc: ./parts/a.md\n---\n')
    const script = fs.readFileSync(tool, 'utf8')
    const encode = text => Buffer.from(text).toString('base64')
    const result = spawnSync(process.execPath, ['-e', script, entry], { input: `${encode(child)}\t${encode('# Dirty\n---\n# B\n')}\n`, encoding: 'utf8', timeout: 10000 })
    assert.equal(result.status, 0, result.stderr)
    assert.match(result.stdout, /slidev-deck\tready/)
    assert.match(result.stdout, /slidev-deck\tslide/)
    assert(!result.stdout.includes('unavailable'), result.stdout)
    const empty = file('empty.md', '')
    assert((await load(empty)).sources.has(empty))
    file('setup/preparser.ts', 'export default []')
    assert((await load(entry)).issues.some(issue => /preparser/.test(issue.message)))
    console.log('PASS: actual Slidev parser imports, ranges, repeats, hidden slides, overrides, cycles, missing sources and protocol')
  } finally { fs.rmSync(root, { recursive: true, force: true }) }
})().catch(error => { console.error(error); process.exitCode = 1 })
